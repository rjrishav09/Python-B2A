# 1. Variables and Data Types
name = "Alex"          # str (string)
age = 25               # int (integer)
height = 5.9           # float
is_student = True      # bool (boolean)
nothing = None         # NoneType

print(type(name))
print(type(age))
print(type(height))
print(type(is_student))
print(type(nothing))
